package activation

import (
	"os"
)

// writeMarker creates (or truncates) the activation marker file at path.
func writeMarker(path string) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0600)
	if err != nil {
		return err
	}
	return f.Close()
}
